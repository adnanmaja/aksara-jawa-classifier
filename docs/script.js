        function handleDragOver(e) {
            e.preventDefault();
            uploadSection.classList.add('dragover');
        }

        function handleDragLeave(e) {
            e.preventDefault();
            uploadSection.classList.remove('dragover');
        }

        function handleDrop(e) {
            e.preventDefault();
            uploadSection.classList.remove('dragover');
            const file = e.dataTransfer.files[0];
            if (file && file.type.startsWith('image/')) {
                displayImagePreview(file);
            }
        }

        async function displayImagePreview(input) {
            if (typeof input === 'string') { // If its a url from image samples
                const response = await fetch(input);
                const blob = await response.blob();
                const filename = input.split('/').pop() || 'sample.jpg';
                const file = new File([blob], filename, { type: blob.type });

                const reader = new FileReader();
                reader.onload = function(e) {
                    imagePreview.src = e.target.result;
                };
                reader.readAsDataURL(file);

                uploadedImage = file;
            } else if (input instanceof File) { // If its an actual file (e.g from file explorer)
                const reader = new FileReader();
                reader.onload = function(e) {
                    imagePreview.src = e.target.result;
                };
                reader.readAsDataURL(input);
                uploadedImage = input;
            } else {
                console.error('Unsupported input type passed to displayImagePreview');
                return;
            }

            uploadSection.style.display = 'none';
            previewSection.style.display = 'block';
            sampleSection.style.display = 'none';
        }

        async function processImage() {
            // if (!uploadedImage) return;

            // Hide preview and show processing
            previewSection.style.display = 'none';
            processingSection.style.display = 'block';
            resultsSection.style.display = 'none';
            detailsSection.style.display = 'none';

            // API call
            await callOCRAPI(uploadedImage);
        }

        async function callOCRAPI(imageFile) {
            const formData = new FormData();
            formData.append('file', imageFile);
            
            try {
                const response = await fetch('https://aksara-container.politecoast-74d29664.southeastasia.azurecontainerapps.io/', { 
                    method: 'POST',
                    body: formData
                });
                
                if (!response.ok) {
                    throw new Error(`HTTP error! status: ${response.status}`);
                }

                const results = await response.json();
                
                // Store details data globally
                detailsData = results.details;
                
                displayResults(results.prediction); 
            } catch (error) {
                console.error('OCR API Error:', error);
                alert(translations[currentLanguage].errorMessage);
                resetInterface();
            }
        }

